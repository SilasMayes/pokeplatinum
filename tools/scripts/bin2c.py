#!/usr/bin/env python3
"""Embed binary files in a C source file.

usage: bin2c.py OUTPUT.c INPUT...

Each input becomes `const unsigned char <name>[]` and `const unsigned int <name>_size`,
where <name> is the file name with every non-alphanumeric character replaced by '_'.
"""
import os
import re
import sys


def main():
    output, inputs = sys.argv[1], sys.argv[2:]
    lines = ["/* Generated by tools/scripts/bin2c.py. Do not edit. */", ""]
    for path in inputs:
        name = re.sub(r"[^A-Za-z0-9]", "_", os.path.basename(path))
        data = open(path, "rb").read()
        lines.append(f"const unsigned int {name}_size = {len(data)};")
        lines.append(f"const unsigned char {name}[{len(data)}] = {{")
        for i in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        lines.append("};")
        lines.append("")
    with open(output, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
